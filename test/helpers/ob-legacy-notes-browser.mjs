import assert from 'node:assert/strict'
import { resolve } from 'node:path'

export async function testLegacyNotes(page, base, output) {
  for (const width of [320, 390, 1280]) {
    await page.setViewport({ width, height: 900 })
    await page.goto(base)
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await page.goto(base + '/?legacy-notes', { waitUntil: 'networkidle0' })
    await page.click('nav button:nth-child(2)')
    await page.waitForSelector('.obm-legacy-notes summary')
    await page.$eval('.obm-legacy-notes summary', node => node.scrollIntoView({ block: 'center' }))
    await page.click('.obm-legacy-notes summary')
    await page.waitForSelector('.obm-legacy-fields textarea')
    assert.deepEqual(await page.$$eval('.obm-legacy-fields textarea', fields => fields.map(field => field.value)),
      ['Spricka vid fönster', 'Risk för fukt', 'Kontrollera anslutning'])
    assert.equal(await page.evaluate(() => window.__obMobileTest.calls.some(call => call.kind === 'legacy-note')), false)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: resolve(output, `legacy-notes-${width}.png`), fullPage: true })
    await page.$eval('.obm-legacy-images button', node => node.scrollIntoView({ block: 'center' }))
    await page.click('.obm-legacy-images button')
    await page.waitForFunction(() => document.querySelector('dialog .obm-image-viewer img')?.naturalWidth > 0)
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => !document.querySelector('dialog[open]'))
    await page.$eval('.obm-legacy-fields textarea', node => node.scrollIntoView({ block: 'center' }))
    await page.type('.obm-legacy-fields textarea', ' kompletterad')
    await page.waitForFunction(() => window.__obMobileTest.calls.some(call => call.kind === 'legacy-note'))
    const calls = await page.evaluate(() => window.__obMobileTest.calls.filter(call => call.kind === 'legacy-note'))
    assert.equal(calls[0].id, 'legacy-observation')
    assert.deepEqual(Object.keys(calls[0].patch), ['note'])
    assert.equal(await page.$eval('.obm-legacy-fields label:nth-child(2) textarea', el => el.value), 'Risk för fukt')
    await page.type('input[aria-label="Sök bland noteringar"]', 'saknashelt')
    await page.waitForFunction(() => !document.querySelector('.obm-legacy-notes'))
  }
  await page.goto(base + '/?legacy-notes', { waitUntil: 'networkidle0' })
  await page.click('nav button:nth-child(2)')
  await page.click('.obm-legacy-notes summary')
  await page.evaluate(() => { window.__obMobileTest.failSaves = true })
  await page.type('.obm-legacy-fields textarea', ' offline')
  await page.waitForFunction(() => document.body.textContent.includes('Test save failure'))
  assert.equal(await page.evaluate(() => window.__obMobileTest.calls.some(call => call.kind === 'legacy-note')), false)
  assert.ok(await page.evaluate(() => window.__obMobileTest.hasDrafts()))
  await page.evaluate(() => { window.__obMobileTest.failSaves = false })
  await page.click('.obm-legacy-fields label:nth-child(2) textarea')
  await page.waitForFunction(() => window.__obMobileTest.calls.some(call => call.kind === 'legacy-note'))
  await page.goto(base + '/?legacy-notes&locked', { waitUntil: 'networkidle0' })
  await page.click('nav button:nth-child(2)')
  await page.click('.obm-legacy-notes summary')
  assert.ok(await page.$$eval('.obm-legacy-fields textarea', fields => fields.length === 3 && fields.every(field => field.readOnly)))
  console.log('PASS: existing exterior note text/risk/FTU, field-only autosave, no write on open, search and responsive layouts.')
}
