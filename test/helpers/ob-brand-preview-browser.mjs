import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import puppeteer from 'puppeteer-core'

export async function testBrandPreview(base, output) {
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage()
  const errors = [], external = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') console.log('Browser:', message.text()) })
  await page.setRequestInterception(true)
  page.on('request', request => {
    if (request.url().startsWith('blob:') || new URL(request.url()).origin === base) void request.continue()
    else { external.push(request.url()); void request.abort() }
  })
  async function click(text, selector = 'button', contains = false) {
    for (const element of await page.$$(selector)) {
      const label = await element.evaluate(node => node.textContent.trim())
      if (contains ? label.includes(text) : label === text) { await element.click(); return }
    }
    throw Error(`Missing ${selector}: ${text}`)
  }
  async function layout(label) {
    await page.waitForFunction(() => [...document.querySelectorAll('img')].filter(img => img.getClientRects().length && !img.closest('details:not([open])'))
      .every(img => img.complete && img.naturalWidth > 0))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${label}: document overflow`)
    assert.deepEqual(await page.evaluate(() => [...document.querySelectorAll('.obm-sheet[open], .obm-sheet-body, .obm-root')]
      .filter(node => node.scrollWidth > node.clientWidth + 1).map(node => node.className)), [], `${label}: panel overflow`)
    assert.deepEqual(await page.evaluate(() => [...document.querySelectorAll('.obm-root button, .obm-sheet button')]
      .filter(node => node.checkVisibility() && node.getBoundingClientRect().height < 48)
      .map(node => node.getAttribute('aria-label') || node.textContent)), [], `${label}: short touch target`)
    assert.equal(await page.evaluate(() => [...document.querySelectorAll('img')].filter(img => img.getClientRects().length && !img.closest('details:not([open])'))
      .every(img => img.complete && img.naturalWidth > 0)), true, `${label}: broken image`)
  }
  try {
    for (const width of [320, 360, 390, 430, 1280]) {
      console.log(`Checking ${width}px`)
      if (page.url().startsWith(base)) await page.evaluate(() => { sessionStorage.clear(); history.replaceState(null, '') })
      await page.setViewport({ width, height: 844 })
      await page.goto(`${base}/round?levels&swipe`, { waitUntil: 'networkidle0' })
      await page.evaluate(() => document.fonts.ready)
      await layout(`places ${width}`)
      await page.screenshot({ path: resolve(output, `places-${width}.png`), fullPage: true })
      await page.click('[aria-label="Öppna stegmeny"]')
      await page.waitForSelector('dialog[open]')
      assert.equal(await page.$$('.obm-menu-building').then(rows => rows.length), 4)
      await layout(`menu ${width}`)
      await page.screenshot({ path: resolve(output, `menu-${width}.png`) })
      if (width === 390) {
        await page.focus('.obm-menu-step')
        await page.keyboard.press('Tab')
        assert.equal(await page.evaluate(() => getComputedStyle(document.activeElement).outlineWidth), '3px')
        await page.keyboard.press('Escape')
        await page.waitForFunction(() => !document.querySelector('dialog[open]'))
        assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Öppna stegmeny')
        await page.click('[aria-label="Öppna stegmeny"]')
        await page.waitForSelector('dialog[open]')
      }
      await page.click('dialog [aria-label="Tillbaka"]')
      await click('Badrum', '.obm-place-row', true)
      await page.waitForSelector('.obm-room-header')
      await layout(`room ${width}`)
      await page.screenshot({ path: resolve(output, `room-${width}.png`), fullPage: true })
      await page.click('[data-note-id="note-1"]')
      await page.waitForSelector('dialog[open] textarea')
      await layout(`note ${width}`)
      await page.screenshot({ path: resolve(output, `note-${width}.png`) })
      assert.equal(await page.$eval('dialog textarea', node => getComputedStyle(node).fontFamily.includes('Manrope')), true)
      assert.equal(await page.$$eval('.obm-photo-actions button', nodes => nodes.length), 3)
      await click('Bildbank')
      await page.waitForSelector('.obm-image-bank-grid')
      await layout(`image bank ${width}`)
      await page.screenshot({ path: resolve(output, `bank-${width}.png`) })
    }
    await page.click('.obm-image-bank-item input')
    await page.click('dialog footer button')
    await page.waitForSelector('dialog[aria-label="Notering"]')
    assert.equal(await page.evaluate(() => window.__obMobileTest.images.filter(image => image.control_item_id === 'note-1').length), 2)
    const chooser = page.waitForFileChooser()
    await click('Välj bilder')
    await (await chooser).accept([resolve('test/fixtures/ob-brand-assets/bathroom-demo.png'), resolve('public/landing/besiktning-editorial-v2.png')])
    await page.waitForFunction(() => window.__obMobileTest.images.filter(image => image.control_item_id === 'note-1').length === 4)
    await page.click('[aria-label="Ta bort bild"]')
    await page.waitForSelector('dialog[aria-label="Ta bort bild"]')
    await click('Ta bort från noteringen')
    await page.waitForSelector('dialog[aria-label="Notering"]')
    assert.equal(await page.evaluate(() => window.__obMobileTest.images.filter(image => image.control_item_id === 'note-1').length), 3)
    await click('Klart')
    await page.waitForFunction(() => !document.querySelector('dialog[open]'))
    await page.click('[aria-label="Flytta rum"]')
    await page.waitForSelector('dialog[open]')
    await layout('move room')
    await page.click('dialog [aria-label="Tillbaka"]')
    await page.click('[aria-label="Byt rumsnamn"]')
    await page.waitForSelector('dialog input')
    await page.$eval('dialog input', node => node.select())
    await page.type('dialog input', 'Badrum och tvättstuga')
    await click('Spara namn')
    await page.waitForFunction(() => document.querySelector('.obm-room-header h1')?.textContent.includes('Badrum och tvättstuga'))
    await page.setViewport({ width: 390, height: 844 })
    await page.evaluate(() => { sessionStorage.clear(); history.replaceState(null, '') })
    await page.goto(`${base}/round?levels&swipe&building=3`, { waitUntil: 'networkidle0' })
    await click('Sovrum', '.obm-place-row', true)
    await layout('long names')
    await page.screenshot({ path: resolve(output, 'long-names-390.png') })
    await page.evaluate(() => { sessionStorage.clear(); history.replaceState(null, '') })
    await page.goto(`${base}/round?levels&swipe&save-error`, { waitUntil: 'networkidle0' })
    await click('Badrum', '.obm-place-row', true)
    await page.click('[data-note-id="note-1"]')
    await page.type('dialog textarea', ' Test av bevarad text.')
    await page.waitForFunction(() => document.querySelector('.obm-error')?.textContent.includes('Kunde inte spara'))
    await layout('save error')
    await page.screenshot({ path: resolve(output, 'save-error-390.png') })
    await page.evaluate(() => { window.__obMobileTest.failSaves = false })
    await click('Försök igen')
    await page.waitForFunction(() => document.querySelector('.obm-saved')?.textContent.includes('Sparad'))
    assert.match(await page.$eval('dialog textarea', node => node.value), /Test av bevarad text/)
    await page.setViewport({ width: 390, height: 430 })
    await page.focus('dialog textarea')
    await layout('reduced viewport for keyboard')
    await page.screenshot({ path: resolve(output, 'keyboard-390.png') })
    await page.setViewport({ width: 320, height: 844 })
    await page.evaluate(() => document.documentElement.setAttribute('data-large-text', ''))
    await layout('200 percent text')
    await page.screenshot({ path: resolve(output, 'text-200.png') })
    await page.evaluate(() => { sessionStorage.clear(); history.replaceState(null, '') })
    await page.goto(`${base}/round?levels&swipe&large-text`, { waitUntil: 'networkidle0' })
    await layout('places with 200 percent text')
    await page.click('[aria-label="Öppna stegmeny"]')
    await page.waitForSelector('dialog[open]')
    await layout('menu with 200 percent text')
    await page.screenshot({ path: resolve(output, 'menu-text-200.png') })
    await page.click('.obm-menu-step[aria-label="ÖB-runda · Gästhus"]')
    await page.waitForFunction(() => new URL(location.href).searchParams.get('building') === '1' && document.querySelector('.obm-page-header > span')?.textContent === 'Gästhus')
    await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'dark' }])
    assert.equal(await page.$eval('.obm-root', node => getComputedStyle(node).colorScheme), 'light')
    await layout('dark device theme retains OB contrast')
    await page.goto(base, { waitUntil: 'networkidle0' })
    await page.waitForSelector('iframe')
    await page.click('#desktop')
    assert.equal(await page.$eval('body', node => node.classList.contains('desktop')), true)
    await page.click('#mobile')
    await page.click('#text')
    assert.equal(await page.$eval('iframe', frame => frame.contentDocument.documentElement.hasAttribute('data-large-text')), true)
    await page.click('#failure')
    assert.equal(await page.$eval('iframe', frame => frame.contentWindow.__obMobileTest.failSaves), true)
    await page.click('#reset')
    await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.querySelector('[data-view="places"]'))
    await page.setViewport({ width: 1280, height: 900 })
    await page.screenshot({ path: resolve(output, 'preview-controls.png') })
    assert.equal((await fetch(`${base}/api/anything`, { method: 'POST' })).status, 405)
    assert.deepEqual(errors, [])
    assert.deepEqual(external, [])
    console.log('PASS: five viewport sizes, four buildings, room/note/image bank, image linking/unlinking, multiple file selection, rename/move sheets, long names, save recovery, reduced height, 200% text, preview controls, no external requests, writes rejected.')
  } catch (error) {
    console.log('Images:', await page.$$eval('img', images => images.map(img => ({ src: img.src, complete: img.complete, width: img.naturalWidth }))))
    console.log('Errors:', errors)
    await page.screenshot({ path: resolve(output, 'failure.png') })
    throw error
  } finally { await browser.close() }
}
