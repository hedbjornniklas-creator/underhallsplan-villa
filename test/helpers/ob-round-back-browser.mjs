import assert from 'node:assert/strict'
import { resolve } from 'node:path'

export async function testRoundBack(page, base, output) {
  const client = await page.createCDPSession()
  const index = async () => (await client.send('Page.getNavigationHistory')).currentIndex
  const back = () => page.evaluate(() => history.back())
  const guarded = () => page.waitForFunction(() => Boolean(history.state?.__obRoundBack))
  const places = () => page.waitForFunction(() => document.querySelector('[data-view="places"]') && !history.state?.__obRoundBack)
  const closed = () => page.waitForFunction(() => !document.querySelector('dialog[open]'))
  const noWrites = async () => assert.deepEqual(await page.evaluate(() => window.__obMobileTest.calls), [])
  async function click(text, parent = '') {
    await page.$$eval(`${parent} button`, (buttons, text) => buttons.find(button => button.textContent.trim() === text || (button.closest('nav') && button.textContent.trim().endsWith(text))).click(), text)
  }
  async function fresh(path = '/?strict') {
    await page.goto(base + '/history-before', { waitUntil: 'networkidle0' })
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await page.goto(base + path, { waitUntil: 'networkidle0' })
    await places()
    await page.evaluate(() => history.replaceState({ ...history.state, __NA: true, __PRIVATE_NEXTJS_INTERNALS_TREE: ['preserved'], testValue: 17 }, ''))
    return index()
  }
  async function room() {
    await page.click('.obm-place-row')
    await page.waitForSelector('.obm-room-header')
    await guarded()
  }
  async function leftInspection() {
    await page.waitForFunction(() => location.pathname === '/history-before')
    assert.equal(await page.$eval('h1', node => node.textContent), 'Besiktningar')
  }
  try {
    await page.setViewport({ width: 390, height: 820 })
    const baseIndex = await fresh()
    await room()
    assert.equal(await index(), baseIndex + 1)
    assert.deepEqual(await page.evaluate(() => { const { __obRoundBack, ...state } = history.state; return state }), { __NA: true, __PRIVATE_NEXTJS_INTERNALS_TREE: ['preserved'], testValue: 17 })
    await back()
    await places()
    assert.equal(await index(), baseIndex, 'room Back returns to places within the same inspection')
    assert.equal(new URL(page.url()).pathname, '/')
    for (let i = 0; i < 3; i++) {
      await room()
      assert.equal(await index(), baseIndex + 1, 'reopening rooms reuses a single boundary')
      await page.click('[aria-label="Till platser"]')
      await places()
      assert.equal(await index(), baseIndex, 'the in-app arrow also removes its history entry')
    }
    await page.evaluate(() => history.forward())
    await places()
    assert.equal(await index(), baseIndex, 'forward cannot strand the user on a retired boundary')
    await room()
    const owner = await page.evaluate(() => history.state.__obRoundBack.owner)
    await page.reload({ waitUntil: 'networkidle0' })
    await page.waitForSelector('.obm-room-header')
    await guarded()
    assert.equal(await page.evaluate(() => history.state.__obRoundBack.owner), owner, 'reload adopts the existing entry')
    assert.equal(await index(), baseIndex + 1)
    await page.click('[aria-label="Byt rumsnamn"]')
    await page.waitForSelector('dialog[open]')
    await back()
    await closed()
    assert.ok(await page.$('.obm-room-header'), 'dialog Back stays in the room')
    await page.click('[data-note-id="note-1"]')
    await page.waitForSelector('dialog[aria-label="Notering"]')
    await click('Bildbank', 'dialog')
    await page.waitForSelector('dialog[aria-label="Bildbank"]')
    await back()
    await page.waitForSelector('dialog[aria-label="Notering"]')
    await back()
    await closed()
    await page.click('.obm-place-images summary')
    await page.click('.obm-place-image')
    await page.waitForSelector('dialog[aria-label="Bild"]')
    await back()
    await closed()
    assert.ok(await page.$('.obm-room-header'))
    await noWrites()
    await back()
    await places()
    await page.click('[aria-label="Lägg till rum"]')
    await page.waitForSelector('dialog[open]')
    await guarded()
    await back()
    await closed()
    await places()
    for (const label of ['Noteringar', 'Att bearbeta']) {
      await click(label, 'nav')
      await guarded()
      await back()
      await places()
    }
    await noWrites()
    await back()
    await leftInspection()

    // The real page's draft-history guard and the real mobile editor share one boundary.
    const integration = '/navigation?round=mobile-v2&history-integration'
    const realBase = await fresh(integration)
    await room()
    await page.click('[data-note-id="note-1"]')
    await page.waitForSelector('dialog textarea')
    await page.evaluate(() => { window.__obMobileTest.failSaves = true })
    await page.click('dialog textarea', { clickCount: 3 })
    await page.keyboard.press('Backspace')
    await page.type('dialog textarea', 'Text som inte far tappas vid Back')
    await page.waitForSelector('dialog [role="alert"]')
    await page.waitForFunction(start => performance.now() > start + 1300, {}, await page.evaluate(() => performance.now()))
    assert.equal(await index(), realBase + 1, 'the page draft guard does not push a competing entry')
    for (let i = 0; i < 2; i++) {
      await back()
      await guarded()
      await page.waitForSelector('dialog [role="alert"]')
      assert.equal(await page.$eval('dialog textarea', node => node.value), 'Text som inte far tappas vid Back')
      assert.equal(await page.evaluate(() => window.__obMobileTest.hasDrafts()), true)
      assert.equal(await index(), realBase + 1)
    }
    await page.screenshot({ path: resolve(output, 'back-save-failure.png') })
    await page.evaluate(() => { window.__obMobileTest.failSaves = false; window.__obMobileTest.delayMs = 1200 })
    await back()
    await page.waitForFunction(() => document.querySelector('dialog [aria-label="Tillbaka"]').disabled)
    await back()
    await guarded()
    await closed()
    assert.ok(await page.$('.obm-room-header'))
    assert.equal(await page.evaluate(() => window.__obMobileTest.notes.find(note => note.id === 'note-1').note), 'Text som inte far tappas vid Back')
    assert.equal(await page.evaluate(() => window.__obMobileTest.hasDrafts()), false)
    await back()
    await places()
    await back()
    await leftInspection()

    const unmountBase = await fresh(integration)
    await click('Att bearbeta', 'nav')
    await guarded()
    await page.click('[aria-label="Öppna stegmeny"]')
    await page.waitForSelector('[role="dialog"]')
    await page.evaluate(() => [...document.querySelectorAll('[role="dialog"] button')].find(button => button.firstElementChild?.textContent === 'Fastighet & uppdrag').click())
    await page.waitForSelector('[data-selected-ob-section="grunddata"]')
    await page.waitForFunction(() => !history.state?.__obRoundBack)
    assert.equal(await index(), unmountBase, 'switching steps cleans up without an invisible Back step')
    await back()
    await leftInspection()
    console.log('PASS: browser Back through rooms/dialogs, root exit, arrows/reopen/reload/Strict Mode, step cleanup, router metadata, failed/slow saves and real page draft-guard coordination.')
  } finally {
    await client.detach()
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
  }
}
