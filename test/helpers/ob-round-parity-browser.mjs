import assert from 'node:assert/strict'
import { resolve } from 'node:path'

export async function testRoundParity({ page, click, fresh, fill, noOverflow, output }) {
  async function waitSheet(title) {
    await page.waitForSelector(`dialog[aria-label="${title}"][open]`)
    assert.ok(await page.$('dialog header [aria-label="Tillbaka"]'))
    assert.equal(await page.$eval('body', node => getComputedStyle(node).overflowY), 'hidden')
    assert.ok(await page.$eval('dialog header', node => {
      const back = node.querySelector('[aria-label="Tillbaka"]').getBoundingClientRect()
      const title = node.querySelector('h2').getBoundingClientRect()
      return back.right <= title.left && title.right <= node.getBoundingClientRect().right
    }))
    await noOverflow()
  }
  const closed = () => page.waitForFunction(() => !document.querySelector('dialog[open]'))
  async function imageSheet() {
    await click('Att bearbeta', 'nav')
    await page.click('.obm-image-row')
    await waitSheet('Koppla bild')
  }
  await fresh()
  await page.click('.obm-place-row')
  await page.click('[aria-label="Flytta rum"]')
  await waitSheet('Flytta rum')
  await page.select('[aria-label="Till plan"]', 'plan2')
  await click('Avbryt', 'dialog')
  await closed()
  assert.equal(await page.evaluate(() => window.__obMobileTest.calls.length), 0)
  await page.click('[aria-label="Flytta rum"]')
  await page.select('[aria-label="Till plan"]', 'plan2')
  await click('Flytta rum', 'dialog footer')
  await closed()
  assert.equal(await page.evaluate(() => window.__obMobileTest.rooms[0].floor_label), 'plan2')
  assert.equal(await page.evaluate(() => window.__obMobileTest.notes[0].interior_room_id), 'room-1')
  await page.click('[aria-label="Radera rum"]')
  await waitSheet('Radera rum')
  await page.waitForSelector('dialog [role="alert"]')
  assert.equal(await page.$eval('dialog .obm-danger', node => node.disabled), true)
  await click('Avbryt', 'dialog')
  await closed()

  // Move flushes the editor first and keeps linked photos with the note.
  await fresh()
  await imageSheet()
  await page.click('input[value="note-1"]')
  await click('Koppla till notering', 'dialog')
  await closed()
  await click('Platser', 'nav')
  await page.click('.obm-place-row')
  await page.click('[data-note-id="note-1"]')
  await fill('dialog textarea', 'Text före flytt')
  await page.click('[aria-label="Flytta notering"]')
  await waitSheet('Flytta notering')
  await page.select('[aria-label="Plan"]', 'plan2')
  await page.select('[aria-label="Till rum"]', 'room-2')
  await click('Flytta notering', 'dialog footer')
  await waitSheet('Notering')
  assert.deepEqual(await page.evaluate(() => {
    const qa = window.__obMobileTest, note = qa.notes.find(row => row.id === 'note-1')
    return [note.interior_room_id, note.note, qa.images[0].interior_room_id]
  }), ['room-2', 'Text före flytt', 'room-2'])
  await page.click('dialog [aria-label="Radera bild"]')
  await waitSheet('Radera bild')
  await click('Avbryt', 'dialog')
  await waitSheet('Notering')
  assert.equal(await page.evaluate(() => window.__obMobileTest.images.length), 1)
  await page.click('[aria-label="Radera notering"]')
  await waitSheet('Radera notering')
  await page.waitForFunction(() => !document.querySelector('dialog .obm-danger').disabled)
  await page.evaluate(() => { window.__obMobileTest.dropMutationResponse = true })
  await click('Radera notering', 'dialog footer')
  await page.waitForSelector('dialog [role="alert"]')
  await page.waitForFunction(() => !document.querySelector('dialog .obm-danger').disabled)
  await click('Radera notering', 'dialog footer')
  await closed()
  assert.deepEqual(await page.evaluate(() => {
    const qa = window.__obMobileTest, calls = qa.calls.filter(row => row.kind === 'remove')
    return [qa.notes.some(row => row.id === 'note-1'), qa.images[0].control_item_id, calls.length, new Set(calls.map(row => row.id)).size]
  }), [false, null, 2, 1])
  await imageSheet()
  await page.click('[aria-label="Radera bild"]')
  await waitSheet('Radera bild')
  await page.waitForFunction(() => !document.querySelector('dialog .obm-danger').disabled)
  await click('Avbryt', 'dialog')
  await waitSheet('Koppla bild')
  assert.equal(await page.evaluate(() => window.__obMobileTest.images.length), 1)
  await page.click('[aria-label="Radera bild"]')
  await waitSheet('Radera bild')
  await page.waitForFunction(() => !document.querySelector('dialog .obm-danger').disabled)
  await click('Radera bild', 'dialog footer')
  await closed()
  assert.equal(await page.evaluate(() => window.__obMobileTest.images.length), 0)

  // Empty room removal is available inside the room, never on the place list.
  await fresh()
  assert.equal(await page.$('[aria-label="Radera rum"]'), null)
  await page.select('select[aria-label="Plan"]', 'plan2')
  await page.click('.obm-place-row')
  await page.click('[aria-label="Radera rum"]')
  await waitSheet('Radera rum')
  await page.waitForFunction(() => !document.querySelector('dialog .obm-danger').disabled)
  await click('Radera rum', 'dialog footer')
  await closed()
  assert.equal(await page.evaluate(() => window.__obMobileTest.rooms.length), 1)

  // New-image drafts stay local, survive tab changes, and produce no empty note on cancel.
  await fresh()
  await imageSheet()
  await click('Ny notering', 'dialog')
  await page.waitForSelector('textarea[aria-label="Ny notering"]')
  await fill('[aria-label="Ny notering"]', 'Lokalt utkast')
  await click('Befintlig notering', 'dialog')
  await click('Ny notering', 'dialog')
  assert.equal(await page.$eval('[aria-label="Ny notering"]', node => node.value), 'Lokalt utkast')
  assert.equal(await page.evaluate(() => window.__obMobileTest.notes.length), 3)
  await page.click('dialog [aria-label="Tillbaka"]')
  await closed()
  assert.equal(await page.evaluate(() => window.__obMobileTest.calls.some(call => call.kind === 'image-note')), false)
  await imageSheet()
  await click('Ny notering', 'dialog')
  await fill('[aria-label="Sök noteringsförslag"]', 'plåt')
  await page.waitForSelector('[data-new-outcome-id="outcome-1"]')
  await page.click('[data-new-outcome-id="outcome-1"]')
  assert.ok(await page.$eval('[aria-label="Ny notering"]', node => node.value.length > 0))
  await fill('[aria-label="Ny notering"]', 'Justerad text från bild')
  await page.waitForFunction(() => !document.querySelector('dialog footer button').disabled)
  await page.evaluate(() => { window.__obMobileTest.dropMutationResponse = true })
  await click('Skapa och koppla', 'dialog footer')
  await page.waitForSelector('dialog [role="alert"]')
  await page.waitForFunction(() => !document.querySelector('dialog footer button').disabled)
  await click('Skapa och koppla', 'dialog footer')
  await closed()
  assert.deepEqual(await page.evaluate(() => {
    const qa = window.__obMobileTest, created = qa.notes.filter(row => row.note === 'Justerad text från bild')
    const calls = qa.calls.filter(row => row.kind === 'image-note')
    return [created.length, created[0].interior_room_id, created[0].selected_outcome_id, qa.images[0].control_item_id === created[0].id, new Set(calls.map(row => row.id)).size]
  }), [1, 'room-1', 'outcome-1', true, 1])

  for (const width of [320, 360, 390, 430, 1280]) {
    await page.setViewport({ width, height: 820 })
    await fresh()
    await imageSheet()
    await page.click('[aria-label="Radera bild"]')
    await waitSheet('Radera bild')
    await click('Avbryt', 'dialog')
    await waitSheet('Koppla bild')
    await click('Ny notering', 'dialog')
    await fill('[aria-label="Ny notering"]', 'En fri notering med bild på rätt plats.')
    await page.waitForFunction(() => !document.querySelector('dialog footer button').disabled)
    await noOverflow()
    await page.screenshot({ path: resolve(output, `new-image-note-${width}.png`) })
    await click('Skapa och koppla', 'dialog footer')
    await closed()
    assert.equal(await page.evaluate(() => window.__obMobileTest.notes.length), 4)
    await click('Platser', 'nav')
    await page.click('.obm-place-row')
    await page.click('[aria-label="Flytta rum"]')
    await page.select('[aria-label="Till plan"]', 'plan2')
    await noOverflow()
    await page.screenshot({ path: resolve(output, `move-room-${width}.png`) })
    await click('Avbryt', 'dialog')
    await closed()
    await page.click('[data-note-id="note-1"]')
    await waitSheet('Notering')
    await page.click('[aria-label="Flytta notering"]')
    await waitSheet('Flytta notering')
    await page.select('[aria-label="Plan"]', 'plan2')
    await page.select('[aria-label="Till rum"]', 'room-2')
    await noOverflow()
    await click('Avbryt', 'dialog')
    await waitSheet('Notering')
    await page.click('[aria-label="Radera notering"]')
    await waitSheet('Radera notering')
    await click('Avbryt', 'dialog')
    await waitSheet('Notering')
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
    await page.click('[aria-label="Radera rum"]')
    await waitSheet('Radera rum')
    await click('Avbryt', 'dialog')
    await closed()
    await fill('[aria-label="Sök notering"]', 'plåt')
    await page.waitForSelector('[data-outcome-id="outcome-1"]')
    await page.click('[data-outcome-id="outcome-1"] .obm-result-text')
    await waitSheet('Noteringsförslag')
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
    await page.click('[aria-label="Till platser"]')
    await page.click('[aria-label="Lägg till rum"]')
    await waitSheet('Lägg till rum')
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
  }
  await fresh('?queued')
  await page.click('.obm-place-row')
  await page.click('[aria-label="Flytta rum"]')
  await page.select('[aria-label="Till plan"]', 'plan2')
  assert.equal(await page.$eval('dialog .obm-primary', node => node.disabled), true)
  await click('Avbryt', 'dialog')
  await closed()
  await page.click('[data-note-id="note-1"]')
  await page.evaluate(() => { window.__obMobileTest.failSaves = true })
  await fill('dialog textarea', 'Osparad text får inte tappas')
  await page.click('[aria-label="Flytta notering"]')
  await page.waitForSelector('dialog [role="alert"]')
  assert.ok(await page.$('dialog[aria-label="Notering"]'))
  assert.equal(await page.evaluate(() => window.__obMobileTest.calls.some(call => call.kind === 'move')), false)
  await page.evaluate(() => { window.__obMobileTest.failSaves = false })
  await page.click('dialog [aria-label="Tillbaka"]')
  await closed()
  console.log('PASS: mockup parity: moves, deletions, image-note tabs, free/catalog text, cancellation, retry IDs, save guards and 320-1280px layouts.')
}
