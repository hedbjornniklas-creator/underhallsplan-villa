import assert from 'node:assert/strict'
import { resolve } from 'node:path'

export async function testRoomNameImages(page, base, output) {
  const rename = 'dialog[aria-label="Byt rumsnamn"]', viewer = 'dialog[aria-label="Bild"]'
  async function fresh(query = '') {
    await page.goto(base, { waitUntil: 'networkidle0' })
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await page.goto(`${base}/?room-images${query}`, { waitUntil: 'networkidle0' })
    await page.click('.obm-place-row')
  }
  async function fill(value) {
    await page.click(`${rename} input`, { clickCount: 3 })
    await page.keyboard.press('Backspace')
    await page.type(`${rename} input`, value)
  }
  const closed = () => page.waitForFunction(() => !document.querySelector('dialog[open]'))
  for (const width of [320, 390, 1280]) {
    await page.setViewport({ width, height: 820 })
    await fresh()
    const before = await page.evaluate(() => ({ room: window.__obMobileTest.rooms[0], notes: window.__obMobileTest.notes, images: window.__obMobileTest.images }))
    await page.click('[aria-label="Byt rumsnamn"]')
    await page.waitForSelector(rename)
    assert.equal(await page.$eval(`${rename} input`, node => node.value), 'Hall')
    await fill('Avbrutet namn')
    await page.click(`${rename} [aria-label="Tillbaka"]`)
    await closed()
    assert.equal(await page.evaluate(() => window.__obMobileTest.calls.length), 0)
    await page.click('[aria-label="Byt rumsnamn"]')
    await fill(' ')
    assert.ok(await page.$eval(`${rename} footer button`, node => node.disabled))
    const name = 'Hall vid sovrummet med ett mycket långt rumsnamn'
    await fill(name)
    await page.screenshot({ path: resolve(output, `room-rename-${width}.png`) })
    await page.evaluate(() => { window.__obMobileTest.holdRename = true })
    await page.click(`${rename} footer button`)
    await page.waitForFunction(() => document.querySelector('dialog [aria-label="Tillbaka"]').disabled)
    await page.keyboard.press('Escape')
    assert.ok(await page.$(rename))
    await page.evaluate(() => { window.__obMobileTest.holdRename = false })
    await closed()
    const after = await page.evaluate(() => ({ room: window.__obMobileTest.rooms[0], notes: window.__obMobileTest.notes, images: window.__obMobileTest.images }))
    assert.deepEqual(after, { ...before, room: { ...before.room, room_label: name } })
    assert.equal(await page.$eval('.obm-room-header h1', node => node.textContent), name)
    assert.ok(await page.$eval('.obm-room-header', header => {
      const name = header.querySelector('h1').getBoundingClientRect(), move = header.querySelector('[aria-label="Flytta rum"]').getBoundingClientRect()
      return name.right <= move.left && header.scrollWidth <= header.clientWidth
    }))
    await page.screenshot({ path: resolve(output, `room-name-${width}.png`) })
    await page.click('.obm-place-images summary')
    assert.deepEqual(await page.$$eval('.obm-place-image', rows => rows.map(row => row.dataset.imageId)), ['photo-1', 'room-linked'])
    assert.ok(await page.$eval('.obm-place-images summary', node => node.textContent.includes('1 utan notering')))
    await page.$eval('.obm-place-images', node => node.scrollIntoView({ block: 'start' }))
    await page.waitForFunction(() => [...document.querySelectorAll('.obm-place-image img')].every(img => img.naturalWidth > 0))
    assert.ok(await page.$$eval('.obm-place-images,.obm-place-image', rows => rows.every(node => node.scrollWidth <= node.clientWidth + 1)))
    await page.screenshot({ path: resolve(output, `room-images-${width}.png`) })
    await page.click('.obm-place-image[data-image-id="photo-1"]')
    await page.waitForSelector(viewer)
    assert.ok(await page.$eval(`${viewer} .obm-place-label`, node => node.textContent.includes('Hall vid sovrummet')))
    assert.equal(await page.$eval(`${viewer} footer button`, node => node.textContent.trim()), 'Koppla till notering')
    await page.click(`${viewer} footer button`)
    await page.waitForSelector('dialog[aria-label="Koppla bild"]')
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
    assert.ok(await page.$eval('.obm-place-images', node => node.open))
    await page.click('.obm-place-image[data-image-id="room-linked"]')
    await page.waitForSelector(viewer)
    assert.equal(await page.$eval(`${viewer} footer button`, node => node.textContent.trim()), 'Öppna notering')
    await page.click(`${viewer} footer button`)
    await page.waitForSelector('dialog[aria-label="Notering"]')
    assert.equal(await page.$eval('dialog textarea', node => node.value), before.notes[0].note)
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
    assert.equal(await page.evaluate(() => window.__obMobileTest.calls.length), 1)
    await page.click('[aria-label="Till platser"]')
    assert.ok(await page.$eval('.obm-place-row', node => node.textContent.includes(name)))
  }
  await fresh()
  await page.click('[aria-label="Byt rumsnamn"]')
  await fill('Behåll vid fel')
  await page.evaluate(() => { window.__obMobileTest.failRename = true })
  await page.click(`${rename} footer button`)
  await page.waitForSelector(`${rename} [role="alert"]`)
  assert.equal(await page.$eval(`${rename} input`, node => node.value), 'Behåll vid fel')
  assert.equal(await page.evaluate(() => window.__obMobileTest.rooms[0].room_label), 'Hall')
  await page.evaluate(() => { window.__obMobileTest.failRename = false })
  await page.click(`${rename} footer button`)
  await closed()
  for (const flag of ['&locked', '&queued']) {
    await fresh(flag)
    assert.ok(await page.$eval('[aria-label="Byt rumsnamn"]', node => node.disabled))
    await page.click('.obm-place-images summary')
    await page.click('.obm-place-image[data-image-id="photo-1"]')
    await page.waitForSelector(viewer)
    assert.ok(await page.$eval(`${viewer} footer button`, node => node.disabled))
    await page.click('dialog [aria-label="Tillbaka"]')
    await closed()
  }
  await fresh()
  await page.click('[aria-label="Till platser"]')
  await page.$$eval('.obm-segment button', buttons => buttons.find(b => b.textContent.trim() === 'Utsida').click())
  await page.click('.obm-place-row')
  assert.equal(await page.$('[aria-label="Byt rumsnamn"]'), null)
  await page.click('.obm-place-images summary')
  assert.deepEqual(await page.$$eval('.obm-place-image', rows => rows.map(row => row.dataset.imageId)), ['room-outside'])
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
  console.log('PASS: room rename/cancel/retry/guards, preserved relations, place photos/link navigation and 320/390/1280 layouts. Synthetic records only.')
}
